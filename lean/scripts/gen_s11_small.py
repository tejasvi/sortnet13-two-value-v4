#!/usr/bin/env python3
"""Write the Lean modules for the small certificates data/small/certN.s7 (Harder's tool, master
branch, converted by tools/convert.cpp), used to test the pipeline on 5 to 9 channels."""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOUND = {5: 9, 6: 12, 7: 16, 8: 19, 9: 25, 10: 29}

def fnv1a(b):
    h = 0xcbf29ce484222325
    for x in b:
        h = ((h ^ x) * 0x100000001b3) & 0xffffffffffffffff
    return h

for n, b in BOUND.items():
    data = open(os.path.join(root, 'data', 'small', f'cert{n}.s7'), 'rb').read()
    assert max(data) < 128
    open(os.path.join(root, 'S11Small', f'Cert{n}.lean'), 'w').write(f'''import S11Comp
import S11Loader

/-! Harder's certificate for {n} channels ({len(data)} characters). -/

load_cert_chunk Sortnet.S11Small.chunk{n} "data/small/cert{n}.s7" {fnv1a(data)}

namespace Sortnet.S11Small

open Sortnet.S11

def byte{n} (i : Nat) : Nat :=
  if h : (⟨i⟩ : String.Pos.Raw) < chunk{n}.rawEndPos then (chunk{n}.getUTF8Byte ⟨i⟩ h).toNat else 0

def count{n} : Nat := readNum byte{n} 0 4

def offsets{n} : Array Nat := offsets byte{n} count{n}

def cert{n} : Cert := ⟨byte{n}, fun s => offsets{n}.getD s 0⟩

end Sortnet.S11Small
''')
open(os.path.join(root, 'S11Small.lean'), 'w').write(''.join(f'import S11Small.Cert{n}\n' for n in BOUND))
thms = ''.join(f'''
theorem certOK_{n} : certOK cert{n} count{n} 256 {n} {b} = true := by native_decide

/-- `S({n}) ≥ {b}`. -/
theorem S{n}_ge_{b} : ∀ net : Network {n}, net.Sorts → {b} ≤ net.length :=
  sorts_bound_of_LB (certOK_sound certOK_{n})
''' for n, b in BOUND.items())
open(os.path.join(root, 'S13', 'S11', 'Small.lean'), 'w').write(f'''import S11Small
import S13.S11.Final

/-!
# Test of the pipeline on 5 to 10 channels

Certificates produced by Harder's tool give the known values `S(5) ≥ 9`, `S(6) ≥ 12`, `S(7) ≥ 16`,
`S(8) ≥ 19`, `S(9) ≥ 25` and `S(10) ≥ 29` through the same checker and soundness proof as `S(11) ≥ 35`.
Generated by `scripts/gen_s11_small.py`.
-/

namespace Sortnet

open S11 S11Small
{thms}
end Sortnet
''')
print('ok')
