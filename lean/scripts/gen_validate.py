#!/usr/bin/env python3
"""Generate S13/Validate.lean from the standard-form networks in networks.txt of the clean-room
verification.

Usage: gen_validate.py [networks.txt]
The default is ../verification/cleanroom/networks.txt relative to the Lean project, which is where
the file sits in the release repository. Lower bounds P(2,N) >= P come from the closure check
(native_decide); upper bounds P(2,N) <= P from explicit standard networks whose top-two correctness
and costs are checked by `decide`.
"""
import os, re, sys
lean_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
default_src = os.path.join(lean_root, '..', 'verification', 'cleanroom', 'networks.txt')
src = sys.argv[1] if len(sys.argv) > 1 else default_src
P = {3: 3, 4: 4, 5: 6, 6: 6, 7: 7, 8: 7, 9: 8, 10: 8, 11: 8, 12: 9, 13: 9}
lines = open(src).read().split('\n')
nets = {}
for i, l in enumerate(lines):
    m = re.match(r'N=(\d+) P2=(\d+) standard-form, oM=(\d+) om=(\d+)', l)
    if m:
        N, p2, oM, om = map(int, m.groups())
        comps = [tuple(map(int, c.split(','))) for c in re.findall(r'\((\d+,\d+)\)', lines[i + 1])]
        assert p2 == P[N] and oM == N - 1 and om == N - 2
        assert all(a < b < N for a, b in comps)
        nets[N] = comps
out = []
out.append('''import S13.P2_13

/-!
# Validation: `P(2,N)` for `3 ≤ N ≤ 13`

The same closure check that gives `P(2,13) ≥ 9` reproduces the known values
`P(2,N) = 3, 4, 6, 6, 7, 7, 8, 8, 8, 9, 9` for `N = 3, ..., 13`:
* `p2_lower_N : P2AtLeast N P`: the check succeeds at `L = P - 1` (`native_decide`);
* `p2_upper_N : ¬ P2AtLeast N (P + 1)`: an explicit standard network on `N` channels (from the
  clean-room verification, `networks.txt`) is top-two correct with all `|W(x,y)| ≤ P`, checked by
  `decide` in the kernel.

Generated by `scripts/gen_validate.py`.
-/

namespace Sortnet

/-- An explicit top-two correct network with all `|W(x,y)| ≤ L` shows `P(2,n) ≤ L`. -/
theorem not_p2AtLeast_of_net {n L : ℕ} (net : GNetwork n) (oM om : Fin n) (h : oM ≠ om)
    (hT : ∀ x y : Fin n, x ≠ y →
      net.eval (runInput n x y) oM = n + 1 ∧ net.eval (runInput n x y) om = n)
    (hW : ∀ x y : Fin n, x ≠ y → (net.W x y).length ≤ L) : ¬ P2AtLeast n (L + 1) := by
  intro hP
  obtain ⟨x, y, hxy, hL⟩ := hP net ⟨oM, om, h, hT⟩
  have := hW x y hxy
  omega
''')
for N in range(3, 14):
    p = P[N]
    comps = nets[N]
    body = ', '.join(f'⟨{a}, {b}, by decide⟩' for a, b in comps)
    out.append(f'''
/-- A standard network on {N} channels, top-two correct with `p₂ = {p}` ({len(comps)} comparators). -/
def net{N} : Network {N} := [{body}]
''')
    if N <= 12:
        out.append(f'''
theorem p2_lower_{N} : P2AtLeast {N} {p} :=
  p2AtLeast_of_not_feasible (not_feasible_of_fullCheck (by native_decide))
''')
    out.append(f'''
theorem p2_upper_{N} : ¬ P2AtLeast {N} ({p} + 1) :=
  not_p2AtLeast_of_net (Network.toG net{N}) {N-1} {N-2} (by decide) (by decide) (by decide)
''')
out.append('''
/-- `P(2,N) = P`. -/
def P2Eq (N P : ℕ) : Prop := P2AtLeast N P ∧ ¬ P2AtLeast N (P + 1)

/-- **`P(2,N)` for `3 ≤ N ≤ 13`**: `3, 4, 6, 6, 7, 7, 8, 8, 8, 9, 9`. -/
theorem p2_values :
    P2Eq 3 3 ∧ P2Eq 4 4 ∧ P2Eq 5 6 ∧ P2Eq 6 6 ∧ P2Eq 7 7 ∧ P2Eq 8 7 ∧ P2Eq 9 8 ∧ P2Eq 10 8 ∧
      P2Eq 11 8 ∧ P2Eq 12 9 ∧ P2Eq 13 9 :=
  ⟨⟨p2_lower_3, p2_upper_3⟩, ⟨p2_lower_4, p2_upper_4⟩, ⟨p2_lower_5, p2_upper_5⟩,
    ⟨p2_lower_6, p2_upper_6⟩, ⟨p2_lower_7, p2_upper_7⟩, ⟨p2_lower_8, p2_upper_8⟩,
    ⟨p2_lower_9, p2_upper_9⟩, ⟨p2_lower_10, p2_upper_10⟩, ⟨p2_lower_11, p2_upper_11⟩,
    ⟨p2_lower_12, p2_upper_12⟩, ⟨P2_13, p2_upper_13⟩⟩

end Sortnet
''')
open(os.path.join(lean_root, 'S13', 'Validate.lean'), 'w').write(''.join(out))
print('wrote S13/Validate.lean for N =', sorted(nets))
